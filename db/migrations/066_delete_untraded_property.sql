-- =============================================================================
-- 066_delete_untraded_property.sql
--   A property that has never traded can be removed. One that has, cannot.
-- =============================================================================
-- `app.forbid_hotel_delete()` refused every delete, unconditionally, with
-- "A property is deactivated, never deleted." That is exactly right for a
-- hotel that has taken a guest: reservations, folios, invoices and eighteen
-- months of audit rows all name it, and removing the row turns a bill into
-- an orphan.
--
-- It is wrong for the other case, and the other case is common. Commissioning
-- a property means typing a three-letter code, and a code typed wrong is
-- scaffolding, not history. Two of these — AGR and PUN — existed only to
-- prove that one hotel cannot read another's rows, a job that now belongs to
-- the scratch database `db/tests/run.sh` builds and drops.
--
-- Deactivating them was the only option the schema offered, and it is the
-- wrong shape: a deactivated property still appears in every list that has a
-- reason to show inactive rows, still holds its code against a real hotel
-- that might want it, and still answers "yes" to `db/preflight`'s question
-- about whether test properties are present.
--
-- So the guard learns to look. It refuses when there is anything to lose and
-- SAYS WHAT IT FOUND — Rule 6: a blocked action is shown with its reason,
-- and the reason is specific enough to act on.
--
-- What deliberately does NOT count as history:
--
--   room_status_log and housekeeping_assignments   generated by creating a
--                                                  room, not by trading
--   audit_log                                      has no foreign key here on
--                                                  purpose. The rows saying
--                                                  this property was created
--                                                  and then removed SURVIVE
--                                                  the delete, which is the
--                                                  whole point of an audit
--                                                  trail. 86 such rows exist
--                                                  for AGR and PUN today and
--                                                  they stay.
-- =============================================================================

create or replace function app.forbid_hotel_delete()
returns trigger
language plpgsql
as $$
declare
  evidence text;
begin
  -- Everything that means a real person did a real thing here. Counted in
  -- one pass so the message can name all of it at once — a refusal that
  -- reveals one blocker at a time makes you delete in a loop to find the
  -- next.
  select string_agg(format('%s %s', w.n, w.label), ', ' order by w.label)
    into evidence
    from (
      select 'reservations'    as label, count(*) as n from reservations    where hotel_id = old.id
      union all select 'folios',         count(*) from folios              where hotel_id = old.id
      union all select 'postings',       count(*) from folio_postings      where hotel_id = old.id
      union all select 'invoices',       count(*) from invoices            where hotel_id = old.id
      union all select 'payments',       count(*) from payments            where hotel_id = old.id
      union all select 'restaurant orders', count(*) from pos_orders       where hotel_id = old.id
      union all select 'banquet events', count(*) from banquet_events      where hotel_id = old.id
      union all select 'night audits',   count(*) from night_audit_runs    where hotel_id = old.id
      union all select 'cashier shifts', count(*) from cashier_shifts      where hotel_id = old.id
      union all select 'till day ends',  count(*) from pos_day_ends        where hotel_id = old.id
      union all select 'work orders',    count(*) from work_orders         where hotel_id = old.id
    ) w
   where w.n > 0;

  if evidence is not null then
    raise exception
      'A property that has traded is deactivated, never deleted.'
      using detail = format('%s still has %s.', old.code, evidence),
            hint   = 'update hotels set is_active = false where code = '
                     || quote_literal(old.code);
  end if;

  -- Nothing was ever sold here. Rooms, room types, rate rows, the menu and
  -- the staff links go with it by cascade; the audit trail does not.
  return old;
end $$;

comment on function app.forbid_hotel_delete() is
  'Refuses to delete a property that has traded, naming what it found. A '
  'property with no reservations, folios, invoices, payments, orders, '
  'events, audits, shifts or work orders is commissioning scaffolding and '
  'may be removed. Audit rows survive either way — they have no foreign key '
  'here for exactly that reason.';


-- -----------------------------------------------------------------------------
-- The sanctioned way to call it
-- -----------------------------------------------------------------------------
-- A raw `delete from hotels` needs the caller to know the code is right, that
-- the row exists, and to read a trigger's exception. This wraps it so the API
-- gets one call and a plain answer, and so the count of what went is reported
-- rather than guessed at.
create or replace function app.delete_property(p_code text)
returns table (removed_code text, rooms int, room_types int, staff_links int)
language plpgsql
security definer
set search_path = public, app, pg_temp
as $$
declare
  h_id uuid;
begin
  select id into h_id from hotels where code = p_code;
  if h_id is null then
    raise exception 'No property with code %.', p_code
      using hint = 'Codes are case-sensitive; check the property list.';
  end if;

  -- Counted BEFORE the delete, because after it there is nothing to count.
  select p_code,
         (select count(*)::int from rooms        where hotel_id = h_id),
         (select count(*)::int from room_types   where hotel_id = h_id),
         (select count(*)::int from staff_hotels where hotel_id = h_id)
    into removed_code, rooms, room_types, staff_links;

  -- The trigger above decides whether this is allowed, and says why if not.
  delete from hotels where id = h_id;

  return next;
end $$;

comment on function app.delete_property(text) is
  'Removes a property that has never traded, returning what went with it. '
  'Raises with a specific reason when the property has history — see '
  'app.forbid_hotel_delete().';
